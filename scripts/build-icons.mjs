// Regenerates js/ui/icons.js from Framework7 Icons (MIT), a set drawn after Apple's SF Symbols.
// SF Symbols themselves may only ship inside apps built with Apple's SDKs, not on a website.
// Usage: npm pack framework7-icons@5.0.5 && tar -xzf framework7-icons-5.0.5.tgz
//        node scripts/build-icons.mjs package/svg

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

// App icon name → Framework7 file (named like the SF Symbol it mirrors).
const MAP = {
  today: 'flame_fill', map: 'map_fill', week: 'calendar', gear: 'gear_alt_fill',
  heart: 'heart_fill', bed: 'bed_double_fill', bolt: 'bolt_fill', drop: 'drop_fill',
  timer: 'timer', speed: 'speedometer', flag: 'flag_fill', location: 'location_fill',
  house: 'house_fill', refresh: 'arrow_2_circlepath', shuffle: 'shuffle',
  external: 'arrow_up_right', chevron: 'chevron_right', close: 'xmark', check: 'checkmark_alt',
  plus: 'plus', minus: 'minus', lock: 'lock_fill', info: 'info_circle_fill',
  warn: 'exclamationmark_triangle_fill', good: 'checkmark_seal_fill', sparkles: 'sparkles',
  court: 'sportscourt_fill', wifiOff: 'wifi_slash', wind: 'wind', thermo: 'thermometer',
  sun: 'sun_max_fill', moon: 'moon_fill', cloudSun: 'cloud_sun_fill', cloudMoon: 'cloud_moon_fill',
  cloud: 'cloud_fill', fog: 'cloud_fog_fill', drizzle: 'cloud_drizzle_fill', rain: 'cloud_rain_fill',
  heavyRain: 'cloud_heavyrain_fill', snow: 'cloud_snow_fill', storm: 'cloud_bolt_rain_fill',
  search: 'search', clock: 'clock',
};

const [dir] = process.argv.slice(2);
if (!dir) throw new Error('Usage: build-icons.mjs <framework7-icons svg dir>');

const entries = await Promise.all(Object.entries(MAP).map(async ([name, file]) => {
  const svg = await readFile(join(dir, `${file}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  if (!inner || /<(script|foreignObject)/i.test(inner)) throw new Error(`Unexpected content in ${file}.svg`);
  return `  ${name}: '${inner.replace(/'/g, "\\'")}',`;
}));

await writeFile(new URL('../js/ui/icons.js', import.meta.url), `// Generated by scripts/build-icons.mjs — do not edit by hand.
// Framework7 Icons, MIT License, Copyright (c) 2016 Vladimir Kharlampidi.
// Drawn on a 56×56 grid after Apple's SF Symbols.

export const ICON_VIEWBOX = '0 0 56 56';

export const ICONS = {
${entries.join('\n')}
};
`);
process.stdout.write(`${entries.length} icônes écrites dans js/ui/icons.js\n`);
